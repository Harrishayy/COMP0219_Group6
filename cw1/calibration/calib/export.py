"""Calibration file export (SPEC §5): JSON record, C header (CAL_<UPPER_NAME>), and SET command script."""
from __future__ import annotations

import json
import math
import shutil
from datetime import datetime, timezone
from pathlib import Path

from . import models

ROOT = Path(__file__).resolve().parents[1]          # calibration/
EXPORT_DIR = ROOT / "exports"
FIRMWARE_HEADER = ROOT.parent / "firmware" / "include" / "calibration_generated.h"

# Never pushed over SET: the board measures its own tare (TARE). Still written to the header (from the
# board's #cal reply) so a reflash boots with the last tare.
NOT_PUSHED = {"lc_offset"}


def exportable(params: dict) -> dict:
    """Firmware values to write/push: everything the board takes except the inactive smoother's parameter."""
    p = {**models.default_params(), **params}
    skip = {"lpf_hz" if models.filter_kind_of(p) == models.FILTER_EMA else "ema_alpha"}
    out = {n: float(p[n]) for n in models.FIRMWARE_PARAMS if n not in skip and math.isfinite(float(p[n]))}
    out["filter_kind"] = float(models.filter_kind_of(p))
    return out


def push_lines(params: dict) -> list[str]:
    return [f"SET {k} {_num(v)}" for k, v in exportable(params).items() if k not in NOT_PUSHED]


def _num(v: float) -> str:
    return f"{v:.9g}"


def _c_float(v: float) -> str:
    s = _num(v)
    if not any(ch in s for ch in ".eEn"):
        s += ".0"
    return s + "f"


def header_text(params: dict, stamp: str, metrics_after: dict | None = None) -> str:
    lines = ["// Generated by `python -m calib export` — do not edit by hand.", f"// {stamp}  drag plate"]
    if metrics_after and "mse" in metrics_after:
        lines.append(f"// fit: mse={metrics_after['mse']:.5f} bias={metrics_after.get('bias', float('nan')):+.4f} "
                     f"sigma={metrics_after.get('sigma', float('nan')):.4f} (m/s)")
    lines += ["// Overrides the defaults in calibration.h.", "#pragma once", "",
              f"#define AIRSPEED_METHOD {models.METHOD_MACRO}", ""]
    lines += [f"#define CAL_{k.upper()} {_c_float(v)}" for k, v in exportable(params).items()]
    return "\n".join(lines) + "\n"


def write(params: dict, fit_info: dict | None = None, metrics_before: dict | None = None,
          metrics_after: dict | None = None, out_dir: Path | str = EXPORT_DIR, install: bool = False) -> dict:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    now = datetime.now(timezone.utc)
    base = out_dir / f"calibration_{now.strftime('%Y%m%dT%H%M%SZ')}"
    record = {
        "model": models.MODEL_ID,
        "method": models.METHOD_MACRO,
        "params": exportable(params),
        "fit": fit_info or {},
        "metrics_before": metrics_before or {},
        "metrics_after": metrics_after or {},
        "created": now.isoformat(timespec="seconds").replace("+00:00", "Z"),
    }
    paths = {"json": base.with_suffix(".json"), "header": base.with_suffix(".h"), "cmd": base.with_suffix(".cmd")}
    paths["json"].write_text(json.dumps(record, indent=2, default=_jsonable) + "\n")
    hdr = header_text(params, record["created"], metrics_after)
    paths["header"].write_text(hdr)
    paths["latest"] = out_dir / "calibration_generated.h"  # stable name, latest export
    paths["latest"].write_text(hdr)
    paths["cmd"].write_text("\n".join(push_lines(params) + ["GET"]) + "\n")
    if install:
        FIRMWARE_HEADER.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(paths["header"], FIRMWARE_HEADER)
        paths["installed"] = FIRMWARE_HEADER
    return {k: str(v) for k, v in paths.items()}


def load(path: str | Path) -> dict:
    rec = json.loads(Path(path).read_text())
    if rec.get("model") != models.MODEL_ID:
        raise ValueError(f"{path}: not a drag-plate calibration (model {rec.get('model')!r})")
    return rec


def _jsonable(o):
    try:
        return float(o)
    except (TypeError, ValueError):
        return str(o)
