"""Calibration file export (SPEC §5): JSON record, C header (CAL_<UPPER_NAME>), and SET command script."""
from __future__ import annotations

import json
import math
import shutil
from datetime import datetime, timezone
from pathlib import Path

from . import models

ROOT = Path(__file__).resolve().parents[1]          # calibration/
EXPORT_DIR = ROOT / "exports"
FIRMWARE_HEADER = ROOT.parent / "firmware" / "include" / "calibration_generated.h"

# Never pushed over SET from an airflow fit: the board measures its own tare (TARE). It is still
# written to the header (from the board's #cal reply) so a reflash boots with the last tare.
NOT_PUSHED = {"lc_offset"}


# PC-only (rho_ref) or legacy-board-only (lpf_hz: the Butterworth of an unconfigured board) values
NOT_EXPORTED = {"rho_ref", "lpf_hz"}


def exportable(model_id: str, params: dict) -> dict:
    """Firmware values to write/push. The team's smoother is the EMA, so filter_kind is always 1."""
    names = [p.name for p in models.param_specs(model_id)]
    out = {n: float(params[n]) for n in names
           if n in params and n not in NOT_EXPORTED and math.isfinite(float(params[n]))}
    out["filter_kind"] = float(models.FILTER_EMA)
    out.setdefault("ema_alpha", float(models.default_params(model_id)["ema_alpha"]))
    return out


def push_lines(model_id: str, params: dict) -> list[str]:
    """SET lines for the parameters the firmware understands (PC-only ones are skipped)."""
    return [f"SET {k} {_num(v)}" for k, v in exportable(model_id, params).items() if k in models.FIRMWARE_PARAMS and k not in NOT_PUSHED]


def _num(v: float) -> str:
    return f"{v:.9g}"


def _c_float(v: float) -> str:
    s = _num(v)
    if not any(ch in s for ch in ".eEn"):
        s += ".0"
    return s + "f"


def board_method_macro(board_method: str | None, model_id: str) -> str | None:
    """AIRSPEED_METHOD macro for the board's `#cal` method string, if it matches the model."""
    entry = models.BOARD_METHODS.get((board_method or "").lower())
    return entry[0] if entry and entry[1] == model_id else None


def header_text(model_id: str, params: dict, stamp: str, metrics_after: dict | None = None,
                board_method: str | None = None) -> str:
    m = models.MODELS[model_id]
    lines = [
        "// Generated by `python -m calib export` — do not edit by hand.",
        f"// {stamp}  model={model_id}  methods={' | '.join(m.methods)}",
    ]
    if metrics_after and "mse" in metrics_after:
        lines.append(f"// fit: mse={metrics_after['mse']:.5f} bias={metrics_after.get('bias', float('nan')):+.4f} "
                     f"sigma={metrics_after.get('sigma', float('nan')):.4f} (m/s)")
    lines += ["// Overrides the defaults in calibration.h.", "#pragma once", ""]
    macro = board_method_macro(board_method, model_id)
    if macro:
        lines += [f"#define AIRSPEED_METHOD {macro}", ""]
    for k, v in exportable(model_id, params).items():
        note = "" if k in models.FIRMWARE_PARAMS else "  // not a firmware parameter"
        lines.append(f"#define CAL_{k.upper()} {_c_float(v)}{note}")
    return "\n".join(lines) + "\n"


def write(model_id: str, params: dict, fit_info: dict | None = None, metrics_before: dict | None = None,
          metrics_after: dict | None = None, out_dir: Path | str = EXPORT_DIR, install: bool = False,
          board_method: str | None = None) -> dict:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    now = datetime.now(timezone.utc)
    stamp = now.strftime("%Y%m%dT%H%M%SZ")
    base = out_dir / f"calibration_{model_id}_{stamp}"
    record = {
        "model": model_id,
        "method": board_method_macro(board_method, model_id) or models.MODELS[model_id].methods[0],
        "methods": list(models.MODELS[model_id].methods),
        "params": exportable(model_id, params),
        "fit": fit_info or {},
        "metrics_before": metrics_before or {},
        "metrics_after": metrics_after or {},
        "created": now.isoformat(timespec="seconds").replace("+00:00", "Z"),
    }
    paths = {"json": base.with_suffix(".json"), "header": base.with_suffix(".h"), "cmd": base.with_suffix(".cmd")}
    paths["json"].write_text(json.dumps(record, indent=2, default=_jsonable) + "\n")
    hdr = header_text(model_id, params, record["created"], metrics_after, board_method)
    paths["header"].write_text(hdr)
    paths["latest"] = out_dir / "calibration_generated.h"  # stable name, latest export
    paths["latest"].write_text(hdr)
    paths["cmd"].write_text("\n".join(push_lines(model_id, params) + ["GET"]) + "\n")
    if install:
        FIRMWARE_HEADER.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(paths["header"], FIRMWARE_HEADER)
        paths["installed"] = FIRMWARE_HEADER
    return {k: str(v) for k, v in paths.items()}


def load(path: str | Path) -> dict:
    rec = json.loads(Path(path).read_text())
    if rec.get("model") not in models.MODELS:
        raise ValueError(f"{path}: unknown model {rec.get('model')!r}")
    return rec


def _jsonable(o):
    try:
        return float(o)
    except (TypeError, ValueError):
        return str(o)
